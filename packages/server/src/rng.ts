import type { Rng } from '@yahtzee/game-logic';

/** Small seeded random generator (mulberry32), used for predictable dice in tests. */
export function seededRng(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function createRng(seed: number | null): Rng {
  return seed === null ? Math.random : seededRng(seed);
}
